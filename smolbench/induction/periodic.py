def get_periodic_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
    *,
    tokenizer: Tokenizer,
) -> Tuple[Quiz, Quiz, Quiz]:
    """Wrap :func:`get_periodic_prompts` to produce True/False QnA format.

    Parameters
    ----------
    config, prompter, tokenizer
        Forwarded verbatim to :func:`get_periodic_prompts`. See that
        function for why ``tokenizer`` is required.

    Returns
    -------
    Tuple[Quiz, Quiz, Quiz]
        The intensional Quiz, extensional Quiz, and noise-padded
        intensional Quiz, in that order.
    """
    return quizzes_from_prompts(
        get_periodic_prompts(config, prompter, tokenizer=tokenizer), ToF
    )


def get_periodic_numeric_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
    *,
    tokenizer: Tokenizer,
) -> Tuple[Quiz, Quiz, Quiz]:
    """Wrap :func:`get_periodic_prompts` to produce integer-answer QnA format.

    Parameters
    ----------
    config, prompter, tokenizer
        Forwarded verbatim to :func:`get_periodic_prompts`. See that
        function for why ``tokenizer`` is required.

    Returns
    -------
    Tuple[Quiz, Quiz, Quiz]
        The intensional Quiz, extensional Quiz, and noise-padded
        intensional Quiz, in that order.
    """
    return quizzes_from_prompts(
        get_periodic_prompts(config, prompter, tokenizer=tokenizer), Numeric
    )


def get_periodic_zero_info_numeric_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
) -> Quiz:
    """Build the zero-information baseline quiz.

    This function renders the same numeric queries and answers as
    ``get_periodic_numeric_quiz``, but with an EMPTY ``positive_info``
    context. The model gets no rules and no listing, so it cannot compute
    the count from the prompt. This is a chance floor at the bottom of the
    amount-of-positive-information gradient.

    This function stands alone: it returns ONE Quiz, and it does not touch
    the 3-condition ``get_periodic_numeric_quiz`` or the shared
    ``(intens, extens, noise_intens)`` tuple shape. Existing callers, and
    the chromatic benchmark, are unaffected.

    Parameters
    ----------
    config : PeriodicConfig
        The benchmark config (harmonics, labels, seed).
    prompter : Prompter
        Template, static substitutions, and query generator.

    Returns
    -------
    Quiz
        One quiz of numeric-answer questions, each rendered with an empty
        context.
    """
    period_to_label, pos_to_compound = generate_sequence(config)
    return tuple(
        Numeric(
            prompt=prompter.template.safe_substitute(
                build_substitution(query, prompter, "")
            ),
            answer=answer,
        )
        for query, answer in prompter.query_gen(
            period_to_label, pos_to_compound, config.seed
        )
    )


