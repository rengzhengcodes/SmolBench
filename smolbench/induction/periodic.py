"""Periodic-pattern induction benchmark (generalized FizzBuzz).

Overview
--------
This benchmark measures whether a model can answer questions about a
sequence generated by ``n`` overlapping periodic "harmonics" -- the k-th
harmonic fires at every position that is a multiple of k, for k in
1..n, exactly like the classic FizzBuzz game generalized beyond
"every 3" / "every 5". At each position, the active label is the
sep-joined concatenation of every harmonic's label whose period divides
that position (see :func:`generate_sequence`). The sequence is generated
for exactly one full period, i.e. positions 1..lcm(1, 2, ..., n), which is
the shortest span over which every harmonic combination recurs.

Each query asks either whether a given label appears at a given position
(:func:`tof_membership_query_gen`, a True/False quiz via
:func:`get_periodic_quiz`) or how many positions in the sequence contain a
given label (:func:`numeric_count_query_gen`, an integer-answer quiz via
:func:`get_periodic_numeric_quiz`). Both query generators are driven off
the same ``period_to_label`` / ``pos_to_compound`` mappings produced by
:func:`generate_sequence`.

Information conditions
-----------------------
Every quiz is generated in three parallel conditions built from the same
underlying sequence (see :func:`get_periodic_prompts`), so a single query
set can be compared across all three:

- **intensional**: the compact rule form, e.g. "Every 3 positions write
  gerbil." for each harmonic (:func:`_render_intensional`) -- this is the
  "pattern-fitted" representation described in ``README.md``.
- **extensional**: the fully enumerated position -> compound-label lookup
  table, e.g. "Position 6: fizz|buzz|gerbil." for every position in the
  period (:func:`_render_extensional`) -- the exhaustive
  empirical-evidence representation, always at least as long as the
  intensional one.
- **noise_intens**: the same intensional text with random noise appended
  (via ``_common.noise_pad``) so its length matches the extensional
  prompt's. This isolates context length as a confound: any accuracy gap
  between intensional and extensional should not be attributable merely to
  the extensional prompt being longer.

Configuration
-------------
:class:`PeriodicConfig` (n, labels, seed, sep) plus a
``smolbench.induction._common.Prompter`` (prompt template, static
substitutions, and one of the query generators above) together determine a
run; :func:`get_periodic_prompts` is the core generator both quiz wrappers
and the ``__main__`` demo build on. The canonical experiment configs used
for actual eval runs live in the notebooks under ``notebooks/periodic/``
(see ``induction_eval.ipynb``), not in this module -- this module only
supplies the generation machinery and its built-in query generators.

Seed discipline
----------------
Every generator here takes an explicit ``seed`` and constructs a fresh
``np.random.default_rng(seed)`` internally rather than relying on global
RNG state, so a run is fully reproducible from its config. The noise pad
deliberately seeds its own RNG from ``seed + 1``, not ``seed`` directly --
see ``smolbench.induction._common.noise_pad`` for why that offset exists
(it decouples noise consumption from the rest of the pipeline's RNG call
order). The ``__main__`` demo below uses seed 42.

Golden-hash contract
---------------------
Generation is byte-pinned by ``tests/test_golden_quizzes.py`` at the
notebooks' production configs: any change to RNG call order or call count
(label sampling, query sampling, noise padding) changes the generated
bytes and breaks that pin. If a change here breaks the golden test, fix
the change -- never re-baseline the fixture to paper over an unintended
generation drift.
"""

import string
from dataclasses import dataclass
from math import lcm
from typing import TypeAlias, Collection, Iterable, Tuple, Dict

import numpy as np

from smolbench.evals import Quiz, ToF, Numeric, Answer
from smolbench.induction._common import (
    Prompter,
    build_substitution,
    noise_pad,
    quizzes_from_prompts,
    random_labels,
)

# Re-exported for callers configuring the benchmark (the class is shared with
# chromatic so the prompting contract stays identical across benchmarks).
__all__ = [
    "PeriodicConfig",
    "Prompter",
    "generate_sequence",
    "get_periodic_prompts",
    "get_periodic_quiz",
    "get_periodic_numeric_quiz",
    "tof_membership_query_gen",
    "numeric_count_query_gen",
]


# ---------------------------------------------------------------------------
# Type aliases
# ---------------------------------------------------------------------------

Label: TypeAlias = str          # label string for a single harmonic
Period: TypeAlias = int          # period k: fires at positions k, 2k, 3k, …
CompoundLabel: TypeAlias = str   # sep-joined labels active at a position
PeriodToLabel: TypeAlias = Dict[Period, Label]
PosToCompound: TypeAlias = Dict[int, CompoundLabel]


# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class PeriodicConfig:
    """Config for generating some periodic pattern."""

    # Number of harmonics; the k-th harmonic fires at positions k, 2k, 3k, … for k in 1..n.
    n: int
    # Labels for each harmonic: n strings or int n → auto-generate n random labels.
    labels: Collection[Label] | int
    # RNG seed for reproducibility.
    seed: int
    # Separator placed between active labels in compound output; must not appear in any label.
    sep: str = "|"

    def __post_init__(self):
        if self.n < 1:
            raise ValueError("n must be positive.")
        if isinstance(self.labels, int):
            if self.labels != self.n:
                raise ValueError(
                    f"When labels is int it must equal n ({self.n}), got {self.labels}."
                )
            # min_length=2: periodic labels are always multi-character, even
            # for small n where the information-theoretic minimum would
            # allow single letters -- see random_labels' docstring.
            object.__setattr__(
                self,
                "labels",
                random_labels(
                    self.labels, self.seed, charset=_LABEL_CHARSET, min_length=2
                ),
            )
        else:
            object.__setattr__(self, "labels", tuple(self.labels))
        if len(self.labels) != self.n:
            raise ValueError(
                f"Number of labels ({len(self.labels)}) must equal n ({self.n})."
            )
        for lbl in self.labels:
            if self.sep in lbl:
                raise ValueError(
                    f"Label '{lbl}' contains the separator '{self.sep}'."
                )


# Charset restricted to lowercase letters so the default '|' separator is always safe.
_LABEL_CHARSET: str = string.ascii_lowercase


# ---------------------------------------------------------------------------
# Sequence generation
# ---------------------------------------------------------------------------

def _seq_len(n: int) -> int:
    """Returns the period of n harmonics: lcm(1, 2, …, n)."""
    return lcm(*range(1, n + 1))


def generate_sequence(config: PeriodicConfig) -> Tuple[PeriodToLabel, PosToCompound]:
    """
    Returns the period→label mapping and the position→compound mapping.

    The sequence covers exactly one full period: positions 1..lcm(1..n).
    At each position the compound label is the sep-joined concatenation of all labels
    whose period divides that position, in ascending period order.
    """
    period_to_label: PeriodToLabel = {
        k: config.labels[k - 1] for k in range(1, config.n + 1)
    }
    seq_len = _seq_len(config.n)
    pos_to_compound: PosToCompound = {
        pos: config.sep.join(
            period_to_label[k] for k in range(1, config.n + 1) if pos % k == 0
        )
        for pos in range(1, seq_len + 1)
    }
    return period_to_label, pos_to_compound


# ---------------------------------------------------------------------------
# Prompt renderers
# ---------------------------------------------------------------------------

def _render_intensional(period_to_label: PeriodToLabel) -> str:
    """Renders the harmonic rules as human-readable text."""
    return "".join(
        f"Every {k} positions write {label}.\n"
        for k, label in sorted(period_to_label.items())
    )


def _render_extensional(pos_to_compound: PosToCompound) -> str:
    """Renders the sequence as a position-indexed lookup table."""
    return "".join(
        f"Position {pos}: {compound}.\n"
        for pos, compound in sorted(pos_to_compound.items())
    )


# ---------------------------------------------------------------------------
# Core prompt generation
# ---------------------------------------------------------------------------

def get_periodic_prompts(
    config: PeriodicConfig,
    prompter: Prompter,
) -> Iterable[Tuple[str, str, str, Answer]]:
    """
    Generates intensional, extensional, and noise-padded intensional prompts.

    The noise-padded intensional appends random noise so its length matches the
    extensional, ablating context length as a confound. When the prompter sets
    ``extens_template`` it is used for the extensional prompt; otherwise all
    three share ``template``.

    Yields
    ------
    (intens, extens, noise_intens, answer) for each query.
    """
    period_to_label, pos_to_compound = generate_sequence(config)

    intension: str = _render_intensional(period_to_label)
    extension: str = _render_extensional(pos_to_compound)

    noise_intension: str = noise_pad(intension, extension, config.seed)

    for query, answer in prompter.query_gen(period_to_label, pos_to_compound, config.seed):
        intens = prompter.template.safe_substitute(
            build_substitution(query, prompter, intension)
        )
        extens = prompter.resolved_extens_template.safe_substitute(
            build_substitution(query, prompter, extension)
        )
        noise_intens = prompter.template.safe_substitute(
            build_substitution(query, prompter, noise_intension)
        )

        yield intens, extens, noise_intens, answer


# ---------------------------------------------------------------------------
# Quiz wrappers
# ---------------------------------------------------------------------------

def get_periodic_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
) -> Tuple[Quiz, Quiz, Quiz]:
    """
    Wraps get_periodic_prompts to produce True/False QnA format.

    Returns
    -------
    (intensional Quiz, extensional Quiz, noise-padded intensional Quiz)
    """
    return quizzes_from_prompts(get_periodic_prompts(config, prompter), ToF)


def get_periodic_numeric_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
) -> Tuple[Quiz, Quiz, Quiz]:
    """
    Wraps get_periodic_prompts to produce integer-answer QnA format.

    Returns
    -------
    (intensional Quiz, extensional Quiz, noise-padded intensional Quiz)
    """
    return quizzes_from_prompts(get_periodic_prompts(config, prompter), Numeric)


def get_periodic_zero_info_numeric_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
) -> Quiz:
    """Zero-information baseline: the same numeric queries/answers as
    ``get_periodic_numeric_quiz``, but rendered with an EMPTY ``positive_info``
    context -- the model gets no rules and no listing, so the count is not
    computable from the prompt (a chance floor at the bottom of the
    amount-of-positive-information gradient).

    Standalone: returns ONE Quiz and does not touch the 3-condition
    ``get_periodic_numeric_quiz`` or the shared
    ``(intens, extens, noise_intens)`` tuple shape, so existing callers and
    the chromatic benchmark are unaffected.
    """
    period_to_label, pos_to_compound = generate_sequence(config)
    return tuple(
        Numeric(
            prompt=prompter.template.safe_substitute(
                build_substitution(query, prompter, "")
            ),
            answer=answer,
        )
        for query, answer in prompter.query_gen(
            period_to_label, pos_to_compound, config.seed
        )
    )


# ---------------------------------------------------------------------------
# Built-in query generators
# ---------------------------------------------------------------------------

# tof_membership_query_gen samples at most this many queries of EACH polarity
# per quiz, so quiz size stays fixed as n grows (n changes task difficulty and
# the lcm(1..n) context length; it must never silently change sample size --
# the replication design is powered around fixed question counts).
MAX_QUERIES_PER_POLARITY: int = 10


def tof_membership_query_gen(
    period_to_label: PeriodToLabel,
    pos_to_compound: PosToCompound,
    seed: int,
) -> Iterable[Tuple[Dict[str, str], bool]]:
    """
    Yields True/False queries of the form 'Does label appear at position pos?'

    Period-1 labels are always present and are excluded (trivially True).
    Yields at most ``MAX_QUERIES_PER_POLARITY`` True and as many False
    queries (fewer when the pattern admits fewer of either polarity), sampled
    without replacement using ``seed`` -- the query count does NOT scale with
    n or sequence length; see the constant's comment.
    """
    rng = np.random.default_rng(seed)

    true_qs: list = []
    false_qs: list = []

    for pos in sorted(pos_to_compound.keys()):
        for period, label in sorted(period_to_label.items()):
            if period == 1:
                continue  # always True for every position — omit trivial queries
            entry = ({"pos": str(pos), "label": label}, pos % period == 0)
            (true_qs if pos % period == 0 else false_qs).append(entry)

    n = min(len(true_qs), len(false_qs), MAX_QUERIES_PER_POLARITY)
    if n == 0:
        return

    for idx in rng.choice(len(true_qs), n, replace=False):
        yield true_qs[idx]
    for idx in rng.choice(len(false_qs), n, replace=False):
        yield false_qs[idx]


def numeric_count_query_gen(
    period_to_label: PeriodToLabel,
    pos_to_compound: PosToCompound,
    seed: int,
) -> Iterable[Tuple[Dict[str, str], int]]:
    """
    Yields count queries of the form 'How many positions 1..seq_len contain label?'

    The ground-truth answer is floor(seq_len / period) for each label, which is
    always an exact integer since each period divides lcm(1..n).
    """
    seq_len = max(pos_to_compound.keys())
    for period, label in sorted(period_to_label.items()):
        yield {"label": label, "seq_len": str(seq_len)}, seq_len // period


