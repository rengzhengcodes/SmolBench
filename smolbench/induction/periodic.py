"""Periodic-pattern induction benchmark (generalized FizzBuzz).

Overview
--------
This benchmark measures whether a model can answer questions about a
sequence generated by ``n`` overlapping periodic "harmonics" -- the k-th
harmonic fires at every position that is a multiple of k, for k in
1..n, exactly like the classic FizzBuzz game generalized beyond
"every 3" / "every 5". At each position, the active label is the
sep-joined concatenation of every harmonic's label whose period divides
that position (see :func:`generate_sequence`). The sequence is generated
for exactly one full period, i.e. positions 1..lcm(1, 2, ..., n), which is
the shortest span over which every harmonic combination recurs.

Each query asks either whether a given label appears at a given position
(:func:`tof_membership_query_gen`, a True/False quiz via
:func:`get_periodic_quiz`) or how many positions in the sequence contain a
given label (:func:`numeric_count_query_gen`, an integer-answer quiz via
:func:`get_periodic_numeric_quiz`). Both query generators are driven off
the same ``period_to_label`` / ``pos_to_compound`` mappings produced by
:func:`generate_sequence`.

Information conditions
-----------------------
Every quiz is generated in three parallel conditions built from the same
underlying sequence (see :func:`get_periodic_prompts`), so a single query
set can be compared across all three:

- **intensional**: the compact rule form, e.g. "Every 3 positions write
  gerbil." for each harmonic (:func:`_render_intensional`) -- this is the
  "pattern-fitted" representation described in ``README.md``.
- **extensional**: the fully enumerated position -> compound-label lookup
  table, e.g. "Position 6: fizz|buzz|gerbil." for every position in the
  period (:func:`_render_extensional`) -- the exhaustive
  empirical-evidence representation, always at least as long as the
  intensional one.
- **noise_intens**: the same intensional text with whitespace appended (via
  ``_common.token_matched_noise_prompt``) until the RENDERED PROMPT has
  exactly as many tokens as its extensional counterpart, measured with the
  tokenizer of the model under test. This isolates context length as a
  confound: any accuracy gap between intensional and extensional should not
  be attributable merely to the extensional prompt being longer.

Harmonic periods: consecutive vs coprime
----------------------------------------
By default the k-th harmonic has period k for k in 1..n, so the sequence
runs for lcm(1..n) positions. That makes sequence length a step function
of n which is useless as a difficulty dial: lcm(1..10) == lcm(1..9) ==
2520, so n=10 lengthens nothing, while n=11 introduces a new prime and
multiplies the period by 11 (27,720 positions, a ~341k-token extensional
listing that no current checkpoint's context window can hold).

``PeriodicConfig.periods`` replaces 1..n with an explicit PAIRWISE-COPRIME
period set. Coprimality is validated, not assumed, because it is what
collapses lcm to the product -- so the caller dials sequence length
directly (``periods=(1, 3, 4, 5, 7, 11)`` -> 4,620 positions) instead of
accepting whatever lcm(1..n) happens to be. Everything downstream --
renderers, query generators, the noise token-matcher -- is shared verbatim
between the two pathways; they diverge only in :func:`_periods_of`.

Note the density trade-off this buys: pairwise coprimality forbids keeping
both 2 and 4, or both 3 and 9, so a coprime set fires fewer labels per
position than 1..n does. Longer sequences therefore come with sparser
per-position compounds, which is a change in the extensional listing's
character and not only its length.

Configuration
-------------
:class:`PeriodicConfig` (n, labels, seed, sep, periods) plus a
``smolbench.induction._common.Prompter`` (prompt template, static
substitutions, and one of the query generators above) together determine a
run; :func:`get_periodic_prompts` is the core generator both quiz wrappers
and the ``__main__`` demo build on. The canonical experiment configs used
for actual eval runs live in the notebooks under ``notebooks/periodic/``
(see ``induction_eval.ipynb``), not in this module -- this module only
supplies the generation machinery and its built-in query generators.

Seed discipline
----------------
Every generator here takes an explicit ``seed`` and constructs a fresh
``np.random.default_rng(seed)`` internally rather than relying on global
RNG state, so a run is fully reproducible from its config. The noise pad
consumes no RNG at all -- whitespace sized against a token target is
deterministic -- so it neither perturbs nor is perturbed by the sampling
call order. The ``__main__`` demo below uses seed 42.

Tokenizer discipline
--------------------
The noise arm is the one part of generation that depends on something
outside the config: the tokenizer defining the token target. It is a
REQUIRED argument rather than a defaulted one, because a wrong-but-plausible
default (some generic encoding standing in for the served model) would
de-calibrate the length control silently, which is precisely the failure
this arm exists to rule out. Quizzes are therefore per-(seed, model): the
intensional and extensional prompts are identical across models, only
``noise_intens`` varies.

Golden-hash contract
---------------------
Generation is byte-pinned by ``tests/test_golden_quizzes.py`` at the
notebooks' production configs: any change to RNG call order or call count
(label sampling, query sampling) or to the noise-padding scheme changes the
generated bytes and breaks that pin. If a change here breaks the golden
test, fix the change -- never re-baseline the fixture to paper over an
unintended generation drift.
"""

