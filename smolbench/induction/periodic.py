def get_periodic_prompts(
    config: PeriodicConfig,
    prompter: Prompter,
    *,
    tokenizer: Tokenizer,
) -> Iterable[Tuple[str, str, str, Answer]]:
    """Generate intensional, extensional, and noise-padded intensional prompts.

    The noise-padded intensional prompt appends whitespace until it has
    exactly as many tokens as the extensional prompt for the same query.
    This ablates context length as a confound. When the prompter sets
    ``extens_template``, this function uses it for the extensional prompt.
    Otherwise all three prompts share ``template``.

    Parameters
    ----------
    config : PeriodicConfig
        The benchmark config (harmonics, labels, seed).
    prompter : Prompter
        Template, static substitutions, and query generator.
    tokenizer : Tokenizer
        The :class:`~smolbench.evals.tokenization.Tokenizer` that defines
        the noise arm's token target. Use the tokenizer of the model this
        quiz goes to (``tokenization.for_model(model)``). This parameter is
        required by design; see the module docstring's tokenizer
        discipline.

    Yields
    ------
    Tuple[str, str, str, Answer]
        ``(intens, extens, noise_intens, answer)`` for each query.
    """
    period_to_label, pos_to_compound = generate_sequence(config)

    intension: str = _render_intensional(period_to_label)
    extension: str = _render_extensional(pos_to_compound)

    # This probes the pad atom once here, not per query: the atom depends
    # only on the tokenizer, and probing it inside the loop would repeat the
    # same measurements for every question.
    unit: str = choose_whitespace_unit(tokenizer)

    for query, answer in prompter.query_gen(period_to_label, pos_to_compound, config.seed):
        intens = prompter.template.safe_substitute(
            build_substitution(query, prompter, intension)
        )
        extens = prompter.resolved_extens_template.safe_substitute(
            build_substitution(query, prompter, extension)
        )
        # This matches per query, on the RENDERED prompt: the query text
        # substituted into each prompt differs in length, so a single
        # shared pad could not make every noise prompt match its own
        # extensional counterpart. The closure renders exactly as the
        # intensional arm above does, so the two differ only in
        # `positive_info`.
        noise_intens = token_matched_noise_prompt(
            context_renderer(prompter, query),
            intension,
            tokenizer.count(extens),
            tokenizer,
            unit=unit,
        )

        yield intens, extens, noise_intens, answer


