# ---------------------------------------------------------------------------
# Type aliases
# ---------------------------------------------------------------------------

Label: TypeAlias = str          # label string for a single harmonic
Period: TypeAlias = int          # period k: fires at positions k, 2k, 3k, …
CompoundLabel: TypeAlias = str   # sep-joined labels active at a position
PeriodToLabel: TypeAlias = Dict[Period, Label]
PosToCompound: TypeAlias = Dict[int, CompoundLabel]


# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class PeriodicConfig:
    """Config for generating some periodic pattern."""

    # Number of harmonics. With the default periods (None) the k-th harmonic
    # fires at positions k, 2k, 3k, … for k in 1..n; with an explicit `periods`
    # set, n is simply how many periods that set contains.
    n: int
    # Labels for each harmonic: n strings or int n → auto-generate n random labels.
    # Assigned in ascending-period order, so labels[i] belongs to the i-th
    # smallest period (identical to the old labels[k-1] on the 1..n pathway).
    labels: Collection[Label] | int
    # RNG seed for reproducibility.
    seed: int
    # Separator placed between active labels in compound output; must not appear in any label.
    sep: str = "|"
    # Explicit PAIRWISE-COPRIME harmonic periods, replacing the default 1..n.
    # None (the default) means the consecutive-integer pathway, whose generated
    # bytes are pinned by tests/test_golden_quizzes.py -- leave it None and
    # nothing about this class's behaviour changes. See _seq_len_of for why
    # coprimality is enforced rather than merely encouraged.
    periods: Tuple[int, ...] | None = None

    def __post_init__(self):
        if self.n < 1:
            raise ValueError("n must be positive.")
        if self.periods is not None:
            periods = tuple(int(p) for p in self.periods)
            if len(periods) != self.n:
                raise ValueError(
                    f"Number of periods ({len(periods)}) must equal n ({self.n})."
                )
            if len(set(periods)) != len(periods):
                raise ValueError(f"Periods must be distinct, got {periods}.")
            if any(p < 1 for p in periods):
                raise ValueError(f"Periods must be positive, got {periods}.")
            # Pairwise coprimality is the whole point of this pathway: it makes
            # lcm(periods) == prod(periods), so sequence length is a product the
            # caller dials directly instead of the step function lcm(1..n) --
            # which is why n=10 buys nothing (lcm stays 2520) and n=11 jumps 11x
            # straight past every model's context window.
            for i, a in enumerate(periods):
                for b in periods[i + 1:]:
                    if gcd(a, b) != 1:
                        raise ValueError(
                            f"Periods must be pairwise coprime; gcd({a}, {b}) = {gcd(a, b)}. "
                            "Without coprimality lcm(periods) < prod(periods) and the "
                            "sequence length is no longer the product you asked for."
                        )
            object.__setattr__(self, "periods", periods)
        if isinstance(self.labels, int):
            if self.labels != self.n:
                raise ValueError(
                    f"When labels is int it must equal n ({self.n}), got {self.labels}."
                )
            # min_length=2: periodic labels are always multi-character, even
            # for small n where the information-theoretic minimum would
            # allow single letters -- see random_labels' docstring.
            object.__setattr__(
                self,
                "labels",
                random_labels(
                    self.labels, self.seed, charset=_LABEL_CHARSET, min_length=2
                ),
            )
        else:
            object.__setattr__(self, "labels", tuple(self.labels))
        if len(self.labels) != self.n:
            raise ValueError(
                f"Number of labels ({len(self.labels)}) must equal n ({self.n})."
            )
        for lbl in self.labels:
            if self.sep in lbl:
                raise ValueError(
                    f"Label '{lbl}' contains the separator '{self.sep}'."
                )


# Charset restricted to lowercase letters so the default '|' separator is always safe.
_LABEL_CHARSET: str = string.ascii_lowercase


# ---------------------------------------------------------------------------
# Sequence generation
# ---------------------------------------------------------------------------

def _periods_of(config: PeriodicConfig) -> Tuple[int, ...]:
    """Returns the harmonic periods this config asks for, ascending.

    The consecutive-integer default (1..n) and the explicit coprime pathway
    differ ONLY here, so every renderer, query generator and quiz wrapper
    downstream is shared verbatim between the two.
    """
    if config.periods is None:
        return tuple(range(1, config.n + 1))
    return tuple(sorted(config.periods))


def _seq_len_of(config: PeriodicConfig) -> int:
    """Returns the sequence period: lcm of the config's harmonic periods.

    For the default 1..n pathway this is lcm(1..n) -- a step function that
    stalls (lcm(1..10) == lcm(1..9) == 2520) then leaps by a whole new prime
    (lcm(1..11) == 27720). For a pairwise-coprime period set, validated as
    such by PeriodicConfig, lcm degenerates to the product, so the caller
    picks the sequence length directly.
    """
    return lcm(*_periods_of(config))


def generate_sequence(config: PeriodicConfig) -> Tuple[PeriodToLabel, PosToCompound]:
    """
    Returns the period→label mapping and the position→compound mapping.

    The sequence covers exactly one full period: positions 1..lcm(periods),
    which is lcm(1..n) on the default pathway and prod(periods) on the
    coprime pathway. At each position the compound label is the sep-joined
    concatenation of all labels whose period divides that position, in
    ascending period order.

    Labels are assigned to periods in ascending-period order, so
    ``labels[i]`` belongs to the i-th smallest period. On the default
    pathway that is exactly the previous ``labels[k - 1]`` for period k.
    """
    periods = _periods_of(config)
    period_to_label: PeriodToLabel = {
        k: config.labels[i] for i, k in enumerate(periods)
    }
    seq_len = _seq_len_of(config)
    pos_to_compound: PosToCompound = {
        pos: config.sep.join(
            period_to_label[k] for k in periods if pos % k == 0
        )
        for pos in range(1, seq_len + 1)
    }
    return period_to_label, pos_to_compound


# ---------------------------------------------------------------------------
# Prompt renderers
# ---------------------------------------------------------------------------

def _render_intensional(period_to_label: PeriodToLabel) -> str:
    """Renders the harmonic rules as human-readable text."""
    return "".join(
        f"Every {k} positions write {label}.\n"
        for k, label in sorted(period_to_label.items())
    )


def _render_extensional(pos_to_compound: PosToCompound) -> str:
    """Renders the sequence as a position-indexed lookup table."""
    return "".join(
        f"Position {pos}: {compound}.\n"
        for pos, compound in sorted(pos_to_compound.items())
    )


# ---------------------------------------------------------------------------
# Core prompt generation
# ---------------------------------------------------------------------------

def get_periodic_prompts(
    config: PeriodicConfig,
    prompter: Prompter,
    *,
    tokenizer: Tokenizer,
) -> Iterable[Tuple[str, str, str, Answer]]:
    """
    Generates intensional, extensional, and noise-padded intensional prompts.

    The noise-padded intensional appends whitespace until it has exactly as
    many tokens as the extensional prompt for the same query, ablating
    context length as a confound. When the prompter sets ``extens_template``
    it is used for the extensional prompt; otherwise all three share
    ``template``.

    Parameters
    ----------
    config:
        The benchmark config (harmonics, labels, seed).
    prompter:
        Template, static substitutions, and query generator.
    tokenizer:
        The :class:`~smolbench.evals.tokenization.Tokenizer` that defines
        the noise arm's token target -- use the tokenizer of the model this
        quiz will be sent to (``tokenization.for_model(model)``). Required
        by design; see the module docstring's tokenizer discipline.

    Yields
    ------
    (intens, extens, noise_intens, answer) for each query.
    """
    period_to_label, pos_to_compound = generate_sequence(config)

    intension: str = _render_intensional(period_to_label)
    extension: str = _render_extensional(pos_to_compound)

    # Probed once here rather than per query: the pad atom depends only on
    # the tokenizer, and probing it inside the loop would repeat the same
    # measurements for every question.
    unit: str = choose_whitespace_unit(tokenizer)

    for query, answer in prompter.query_gen(period_to_label, pos_to_compound, config.seed):
        intens = prompter.template.safe_substitute(
            build_substitution(query, prompter, intension)
        )
        extens = prompter.resolved_extens_template.safe_substitute(
            build_substitution(query, prompter, extension)
        )
        # Matched per query, on the RENDERED prompt: the query text
        # substituted into each prompt differs in length, so a single shared
        # pad could not make every noise prompt match its own extensional
        # counterpart. The closure renders exactly as the intensional arm
        # above does, so the two differ only in `positive_info`.
        noise_intens = token_matched_noise_prompt(
            context_renderer(prompter, query),
            intension,
            tokenizer.count(extens),
            tokenizer,
            unit=unit,
        )

        yield intens, extens, noise_intens, answer


# ---------------------------------------------------------------------------
# Quiz wrappers
# ---------------------------------------------------------------------------

def get_periodic_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
    *,
    tokenizer: Tokenizer,
) -> Tuple[Quiz, Quiz, Quiz]:
    """
    Wraps get_periodic_prompts to produce True/False QnA format.

    Parameters
    ----------
    config, prompter, tokenizer:
        Forwarded verbatim to :func:`get_periodic_prompts`; see there for
        why ``tokenizer`` is required.

    Returns
    -------
    (intensional Quiz, extensional Quiz, noise-padded intensional Quiz)
    """
    return quizzes_from_prompts(
        get_periodic_prompts(config, prompter, tokenizer=tokenizer), ToF
    )


def get_periodic_numeric_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
    *,
    tokenizer: Tokenizer,
) -> Tuple[Quiz, Quiz, Quiz]:
    """
    Wraps get_periodic_prompts to produce integer-answer QnA format.

    Parameters
    ----------
    config, prompter, tokenizer:
        Forwarded verbatim to :func:`get_periodic_prompts`; see there for
        why ``tokenizer`` is required.

    Returns
    -------
    (intensional Quiz, extensional Quiz, noise-padded intensional Quiz)
    """
    return quizzes_from_prompts(
        get_periodic_prompts(config, prompter, tokenizer=tokenizer), Numeric
    )


def get_periodic_zero_info_numeric_quiz(
    config: PeriodicConfig,
    prompter: Prompter,
) -> Quiz:
    """Zero-information baseline: the same numeric queries/answers as
    ``get_periodic_numeric_quiz``, but rendered with an EMPTY ``positive_info``
    context -- the model gets no rules and no listing, so the count is not
    computable from the prompt (a chance floor at the bottom of the
    amount-of-positive-information gradient).

    Standalone: returns ONE Quiz and does not touch the 3-condition
    ``get_periodic_numeric_quiz`` or the shared
    ``(intens, extens, noise_intens)`` tuple shape, so existing callers and
    the chromatic benchmark are unaffected.
    """
    period_to_label, pos_to_compound = generate_sequence(config)
    return tuple(
        Numeric(
            prompt=prompter.template.safe_substitute(
                build_substitution(query, prompter, "")
            ),
            answer=answer,
        )
        for query, answer in prompter.query_gen(
            period_to_label, pos_to_compound, config.seed
        )
    )


# ---------------------------------------------------------------------------
# Built-in query generators
# ---------------------------------------------------------------------------

# tof_membership_query_gen samples at most this many queries of EACH polarity
# per quiz, so quiz size stays fixed as n grows (n changes task difficulty and
# the lcm(1..n) context length; it must never silently change sample size --
# the replication design is powered around fixed question counts).
MAX_QUERIES_PER_POLARITY: int = 10


def tof_membership_query_gen(
    period_to_label: PeriodToLabel,
    pos_to_compound: PosToCompound,
    seed: int,
) -> Iterable[Tuple[Dict[str, str], bool]]:
    """
    Yields True/False queries of the form 'Does label appear at position pos?'

    Period-1 labels are always present and are excluded (trivially True).
    Yields at most ``MAX_QUERIES_PER_POLARITY`` True and as many False
    queries (fewer when the pattern admits fewer of either polarity), sampled
    without replacement using ``seed`` -- the query count does NOT scale with
    n or sequence length; see the constant's comment.
    """
    rng = np.random.default_rng(seed)

    true_qs: list = []
    false_qs: list = []

    for pos in sorted(pos_to_compound.keys()):
        for period, label in sorted(period_to_label.items()):
            if period == 1:
                continue  # always True for every position — omit trivial queries
            entry = ({"pos": str(pos), "label": label}, pos % period == 0)
            (true_qs if pos % period == 0 else false_qs).append(entry)

    n = min(len(true_qs), len(false_qs), MAX_QUERIES_PER_POLARITY)
    if n == 0:
        return

    for idx in rng.choice(len(true_qs), n, replace=False):
        yield true_qs[idx]
    for idx in rng.choice(len(false_qs), n, replace=False):
        yield false_qs[idx]


def numeric_count_query_gen(
    period_to_label: PeriodToLabel,
    pos_to_compound: PosToCompound,
    seed: int,
) -> Iterable[Tuple[Dict[str, str], int]]:
    """
    Yields count queries of the form 'How many positions 1..seq_len contain label?'

    The ground-truth answer is floor(seq_len / period) for each label, which is
    always an exact integer since seq_len is the lcm of the harmonic periods,
    so every period divides it -- true on both the default 1..n pathway
    (lcm(1..n)) and the explicit coprime one (prod(periods)).
    """
    seq_len = max(pos_to_compound.keys())
    for period, label in sorted(period_to_label.items()):
        yield {"label": label, "seq_len": str(seq_len)}, seq_len // period


