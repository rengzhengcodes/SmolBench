PosToCompound: TypeAlias = Dict[int, CompoundLabel]


# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class PeriodicConfig:
    """Configure the generation of one periodic pattern."""

    # Number of harmonics. With the default periods (None), the k-th
    # harmonic fires at positions k, 2k, 3k, … for k in 1..n. With an
    # explicit `periods` set, n is simply how many periods that set holds.
    n: int
    # Labels for each harmonic: n strings, or int n to auto-generate n
    # random labels. This field assigns labels in ascending-period order, so
    # labels[i] belongs to the i-th smallest period (identical to the old
    # labels[k-1] on the 1..n pathway).
    labels: Collection[Label] | int
    # RNG seed for reproducibility.
    seed: int
    # Separator placed between active labels in compound output. Must not
    # appear in any label.
    sep: str = "|"
    # Explicit harmonic periods, replacing the default 1..n. None (the
    # default) selects the consecutive-integer pathway, whose generated
    # bytes are pinned by tests/test_golden_quizzes.py. Leave it None and
    # nothing about this class's behavior changes.
    periods: Tuple[int, ...] | None = None
    # The sequence length `periods` is expected to produce. Omit it, and the
    # periods must be PAIRWISE COPRIME, so lcm == product, and the length is
    # whatever the caller multiplied out. This is the pathway for making the
    # extensional listing longer. Supply it, and coprimality is NOT
    # required; instead lcm(periods) must equal it exactly. This is what
    # lets a DIVISOR set add harmonics while it pins the sequence length --
    # the pathway for making the INTENSIONAL rule list longer at a fixed
    # extensional listing.
    #
    # Both modes enforce the same underlying discipline: the caller states
    # the length it expects, and construction fails if the periods
    # disagree. This matters because the failure is otherwise invisible --
    # a period set that produces the wrong length still generates a
    # perfectly self-consistent quiz, just not the one that was asked for.
    expect_seq_len: int | None = None

    def __post_init__(self):
        if self.n < 1:
            raise ValueError("n must be positive.")
        if self.periods is not None:
            periods = tuple(int(p) for p in self.periods)
            if len(periods) != self.n:
                raise ValueError(
                    f"Number of periods ({len(periods)}) must equal n ({self.n})."
                )
            if len(set(periods)) != len(periods):
                raise ValueError(f"Periods must be distinct, got {periods}.")
            if any(p < 1 for p in periods):
                raise ValueError(f"Periods must be positive, got {periods}.")
            if self.expect_seq_len is None:
                # Pairwise coprimality is the whole point of this pathway. It
                # makes lcm(periods) == prod(periods), so sequence length is
                # a product the caller dials directly, instead of the step
                # function lcm(1..n). This is why n=10 buys nothing (lcm
                # stays 2520) and n=11 jumps 11x straight past every model's
                # context window.
                for i, a in enumerate(periods):
                    for b in periods[i + 1:]:
                        if gcd(a, b) != 1:
                            raise ValueError(
                                f"Periods must be pairwise coprime; gcd({a}, {b}) = {gcd(a, b)}. "
                                "Without coprimality lcm(periods) < prod(periods) and the "
                                "sequence length is no longer the product you asked for. "
                                "Pass expect_seq_len=<length> to use a non-coprime set on "
                                "purpose (the divisor pathway)."
                            )
            else:
                # Divisor pathway: the periods deliberately SHARE factors so
                # lcm stays put. Each period d contributes seq_len/d
                # occurrences to the extensional listing, so adding large
                # divisors grows the intensional rule list while it leaves
                # the listing ~unchanged.
                actual = lcm(*periods)
                if actual != self.expect_seq_len:
                    raise ValueError(
                        f"lcm(periods) is {actual}, not the declared expect_seq_len "
                        f"{self.expect_seq_len}. Every period must divide the declared "
                        "length (and together they must reach it) or the extensional "
                        "listing silently changes size, which is the one thing this "
                        "pathway exists to hold fixed."
                    )
            object.__setattr__(self, "periods", periods)
        elif self.expect_seq_len is not None:
            raise ValueError(
                "expect_seq_len only means something alongside an explicit `periods` "
                "set; on the default 1..n pathway the length is lcm(1..n) by definition."
            )
        if isinstance(self.labels, int):
            if self.labels != self.n:
                raise ValueError(
                    f"When labels is int it must equal n ({self.n}), got {self.labels}."
                )
            # min_length=2: periodic labels are always multi-character, even
            # for small n where the information-theoretic minimum would
            # allow single letters -- see random_labels' docstring.
            object.__setattr__(
                self,
                "labels",
                random_labels(
                    self.labels, self.seed, charset=_LABEL_CHARSET, min_length=2
                ),
            )
        else:
            object.__setattr__(self, "labels", tuple(self.labels))
        if len(self.labels) != self.n:
            raise ValueError(
                f"Number of labels ({len(self.labels)}) must equal n ({self.n})."
            )
        for lbl in self.labels:
            if self.sep in lbl:
                raise ValueError(
                    f"Label '{lbl}' contains the separator '{self.sep}'."
                )


# This charset is restricted to lowercase letters, so the default '|'
# separator is always safe.
_LABEL_CHARSET: str = string.ascii_lowercase


# ---------------------------------------------------------------------------
# Sequence generation
# ---------------------------------------------------------------------------

def _periods_of(config: PeriodicConfig) -> Tuple[int, ...]:
    """Return the harmonic periods this config asks for, in ascending order.

    The consecutive-integer default (1..n) and the explicit coprime pathway
    differ ONLY here. Every renderer, query generator, and quiz wrapper
    downstream is shared verbatim between the two.

    Parameters
    ----------
    config : PeriodicConfig
        The benchmark config.

    Returns
    -------
    Tuple[int, ...]
        The harmonic periods, in ascending order.
    """
    if config.periods is None:
        return tuple(range(1, config.n + 1))
    return tuple(sorted(config.periods))


def _seq_len_of(config: PeriodicConfig) -> int:
    """Return the sequence period: the lcm of the config's harmonic periods.

    For the default 1..n pathway this is lcm(1..n), a step function that
    stalls (lcm(1..10) == lcm(1..9) == 2520), then leaps by a whole new
    prime (lcm(1..11) == 27720). For a pairwise-coprime period set,
    validated as such by ``PeriodicConfig``, lcm degenerates to the
    product, so the caller picks the sequence length directly.

    Parameters
    ----------
    config : PeriodicConfig
        The benchmark config.

    Returns
    -------
    int
        The sequence length: lcm of the config's harmonic periods.
    """
    return lcm(*_periods_of(config))


def generate_sequence(config: PeriodicConfig) -> Tuple[PeriodToLabel, PosToCompound]:
    """Generate the period-to-label and position-to-compound mappings.

    The sequence covers exactly one full period: positions 1..lcm(periods),
    which is lcm(1..n) on the default pathway and prod(periods) on the
    coprime pathway. At each position, the compound label is the sep-joined
    concatenation of all labels whose period divides that position, in
    ascending period order.

    This function assigns labels to periods in ascending-period order, so
    ``labels[i]`` belongs to the i-th smallest period. On the default
    pathway that is exactly the previous ``labels[k - 1]`` for period k.

    Parameters
    ----------
    config : PeriodicConfig
        The benchmark config (harmonics, labels, seed).

    Returns
    -------
    Tuple[PeriodToLabel, PosToCompound]
        The period-to-label mapping and the position-to-compound mapping.
    """
    periods = _periods_of(config)
    period_to_label: PeriodToLabel = {
        k: config.labels[i] for i, k in enumerate(periods)
    }
    seq_len = _seq_len_of(config)
    pos_to_compound: PosToCompound = {
        pos: config.sep.join(
            period_to_label[k] for k in periods if pos % k == 0
        )
        for pos in range(1, seq_len + 1)
    }
    return period_to_label, pos_to_compound


# ---------------------------------------------------------------------------
# Prompt renderers
# ---------------------------------------------------------------------------

def _render_intensional(period_to_label: PeriodToLabel) -> str:
    """Render the harmonic rules as human-readable text."""
    return "".join(
        f"Every {k} positions write {label}.\n"
        for k, label in sorted(period_to_label.items())
    )


def _render_extensional(pos_to_compound: PosToCompound) -> str:
    """Render the sequence as a position-indexed lookup table."""
    return "".join(
        f"Position {pos}: {compound}.\n"
        for pos, compound in sorted(pos_to_compound.items())
    )


