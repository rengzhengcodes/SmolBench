"""Test periodic-pattern induction (generalized FizzBuzz).

Overview
--------
This benchmark measures whether a model can answer questions about a
sequence generated by ``n`` overlapping periodic "harmonics". The k-th
harmonic fires at every position that is a multiple of k, for k in
1..n, exactly like the classic FizzBuzz game generalized beyond
"every 3" / "every 5". At each position, the active label is the
sep-joined concatenation of every harmonic's label whose period divides
that position (see :func:`generate_sequence`). The sequence covers exactly
one full period, i.e. positions 1..lcm(1, 2, ..., n). This is the shortest
span over which every harmonic combination recurs.

Each query asks either whether a given label appears at a given position
(:func:`tof_membership_query_gen`, a True/False quiz via
:func:`get_periodic_quiz`) or how many positions in the sequence contain a
given label (:func:`numeric_count_query_gen`, an integer-answer quiz via
:func:`get_periodic_numeric_quiz`). A third function,
:func:`get_periodic_zero_info_numeric_quiz`, wraps the same count queries
into a fourth, zero-information quiz that carries no rules or listing at
all (see "Information conditions" below). Both built-in query generators
run off the same ``period_to_label`` / ``pos_to_compound`` mappings that
:func:`generate_sequence` produces.

Information conditions
-----------------------
A single query set can be compared across three parallel conditions, each
built from the same underlying sequence (see :func:`get_periodic_prompts`):

- **intensional**: the compact rule form, e.g. "Every 3 positions write
  gerbil." for each harmonic (:func:`_render_intensional`). This is the
  "pattern-fitted" representation that ``smolbench/induction/README.md``
  describes.
- **extensional**: the fully enumerated position -> compound-label lookup
  table, e.g. "Position 6: fizz|buzz|gerbil." for every position in the
  period (:func:`_render_extensional`). This is the exhaustive
  empirical-evidence representation. It is always at least as long as the
  intensional one.
- **noise_intens**: the same intensional text, with whitespace appended
  (via ``_common.token_matched_noise_prompt``) until the RENDERED PROMPT
  has exactly as many tokens as its extensional counterpart, measured with
  the tokenizer of the model under test. This isolates context length as a
  confound: any accuracy gap between intensional and extensional should not
  come only from the extensional prompt being longer.

A fourth, standalone condition sits below this zero point of the
information gradient: :func:`get_periodic_zero_info_numeric_quiz` renders
the same count queries with an EMPTY context, so the model gets no rules
and no listing at all. It returns one ``Quiz``, not the three-condition
tuple above, so it does not change ``get_periodic_numeric_quiz``'s shape or
any existing caller.

Harmonic periods: consecutive vs coprime
----------------------------------------
By default, the k-th harmonic has period k for k in 1..n, so the sequence
runs for lcm(1..n) positions. That makes sequence length a step function of
n, which is useless as a difficulty dial: lcm(1..10) == lcm(1..9) == 2520,
so n=10 lengthens nothing, while n=11 introduces a new prime and multiplies
the period by 11 (27,720 positions, a ~341k-token extensional listing that
no current checkpoint's context window can hold).

``PeriodicConfig.periods`` replaces 1..n with an explicit period set, in one
of two modes. The two modes are duals: each one lengthens one side of the
intensional/extensional contrast while it holds the other side still.

**Coprime mode** (``periods`` alone). A pairwise-coprime set has lcm ==
product, so the caller dials sequence length directly:
``periods=(1, 3, 4, 5, 7, 11)`` gives 4,620 positions, a ~1.6x longer
EXTENSIONAL listing. This mode validates coprimality; it does not assume
it, because coprimality is exactly what collapses lcm to the product. The
density trade-off it forces is worth knowing: coprimality forbids keeping
both 2 and 4, or both 3 and 9, so such a set fires fewer labels per
position than 1..n does. Longer sequences then arrive with sparser
compounds, a change in the listing's character and not only its length.

**Divisor mode** (``periods`` plus ``expect_seq_len``). Here the periods
deliberately SHARE factors, so lcm stays put, and this mode does not
require coprimality. Instead, lcm must equal the declared length. Because a
period d contributes only seq_len/d occurrences to the listing, adding
LARGE divisors adds intensional rules and questions while the extensional
listing barely moves. Against a 2,520-position baseline: the 9 largest
proper divisors take 9 harmonics to 18 for +0.6% listing growth, and 17 of
them reach 26 harmonics for +2.5%. This lengthens the INTENSIONAL side at a
fixed extensional one. (Its reach is bounded: 2,520 has only 48 divisors,
and taking all of them grows the listing 31%. So "fixed" holds for the
large-divisor end of the range, not the whole of it.)

Both modes enforce one discipline: the caller states the sequence length it
expects, and construction fails if the periods disagree. A period set that
silently produces the wrong length still generates a perfectly
self-consistent quiz, so nothing downstream would ever notice the error.

Everything downstream (renderers, query generators, the noise
token-matcher) is shared verbatim across all three pathways. They diverge
only in :func:`_periods_of`.

Configuration
-------------
:class:`PeriodicConfig` (n, labels, seed, sep, periods), plus a
``smolbench.induction._common.Prompter`` (prompt template, static
substitutions, and one of the query generators above), together determine a
run. :func:`get_periodic_prompts` is the core generator that both quiz
wrappers and the ``__main__`` demo build on. This module only supplies the
generation machinery and its built-in query generators; it does not hold
the canonical configs used for real eval runs. Those live in
``notebooks/induction/run_study.py`` (the current family-ladder scaling
study; see that module's docstring).

Seed discipline
----------------
Every generator here takes an explicit ``seed`` and builds a fresh
``np.random.default_rng(seed)`` internally. It does not rely on global RNG
state, so a run is fully reproducible from its config. The noise pad
consumes no RNG at all, because sizing whitespace against a token target
is deterministic. So it neither perturbs, nor is perturbed by, the sampling
call order. The ``__main__`` demo below uses seed 42.

Tokenizer discipline
--------------------
The noise arm is the one part of generation that depends on something
outside the config: the tokenizer that defines the token target. It is a
REQUIRED argument, not a defaulted one, because a wrong-but-plausible
default (some generic encoding standing in for the served model) would
de-calibrate the length control silently. That is precisely the failure
this arm exists to rule out. Quizzes are therefore per-(seed, model): the
intensional and extensional prompts stay identical across models, and only
``noise_intens`` varies.

Golden-hash contract
---------------------
Generation is byte-pinned by ``tests/test_golden_quizzes.py`` at the
notebooks' production configs. Any change to RNG call order or call count
(label sampling, query sampling), or to the noise-padding scheme, changes
the generated bytes and breaks that pin. If a change here breaks the golden
test, fix the change. Never re-baseline the fixture to paper over an
unintended generation drift.
"""

