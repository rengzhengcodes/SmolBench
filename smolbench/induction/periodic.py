# tof_membership_query_gen samples at most this many queries of EACH
# polarity per quiz, so quiz size stays fixed as n grows. n changes task
# difficulty and the lcm(1..n) context length; it must never silently
# change sample size, because the replication design is powered around
# fixed question counts.
MAX_QUERIES_PER_POLARITY: int = 10


def tof_membership_query_gen(
    period_to_label: PeriodToLabel,
    pos_to_compound: PosToCompound,
    seed: int,
) -> Iterable[Tuple[Dict[str, str], bool]]:
    """Yield True/False queries of the form "Does label appear at position pos?"

    Period-1 labels are always present, so this function excludes them
    (they would be trivially True). It yields at most
    ``MAX_QUERIES_PER_POLARITY`` True queries and as many False queries
    (fewer when the pattern admits fewer of either polarity), sampled
    without replacement using ``seed``. The query count does NOT scale with
    n or sequence length; see the constant's comment.

    Parameters
    ----------
    period_to_label : PeriodToLabel
        Period-to-label mapping from :func:`generate_sequence`.
    pos_to_compound : PosToCompound
        Position-to-compound mapping from :func:`generate_sequence`.
    seed : int
        RNG seed for the sampling.

    Yields
    ------
    Tuple[Dict[str, str], bool]
        A ``({"pos": ..., "label": ...}, answer)`` pair per query.
    """
    rng = np.random.default_rng(seed)

    true_qs: list = []
    false_qs: list = []

    for pos in sorted(pos_to_compound.keys()):
        for period, label in sorted(period_to_label.items()):
            if period == 1:
                continue  # true for every position -- skip this trivial query
            entry = ({"pos": str(pos), "label": label}, pos % period == 0)
            (true_qs if pos % period == 0 else false_qs).append(entry)

    n = min(len(true_qs), len(false_qs), MAX_QUERIES_PER_POLARITY)
    if n == 0:
        return

    for idx in rng.choice(len(true_qs), n, replace=False):
        yield true_qs[idx]
    for idx in rng.choice(len(false_qs), n, replace=False):
        yield false_qs[idx]


def numeric_count_query_gen(
    period_to_label: PeriodToLabel,
    pos_to_compound: PosToCompound,
    seed: int,
) -> Iterable[Tuple[Dict[str, str], int]]:
    """Yield count queries of the form "How many positions 1..seq_len contain label?"

    The ground-truth answer is floor(seq_len / period) for each label. This
    is always an exact integer, because seq_len is the lcm of the harmonic
    periods, so every period divides it. This holds on both the default
    1..n pathway (lcm(1..n)) and the explicit coprime one (prod(periods)).

    Parameters
    ----------
    period_to_label : PeriodToLabel
        Period-to-label mapping from :func:`generate_sequence`.
    pos_to_compound : PosToCompound
        Position-to-compound mapping from :func:`generate_sequence`. This
        function reads only its keys, to find ``seq_len``.
    seed : int
        Unused by this generator (count queries need no sampling), but
        every ``query_gen`` in this module shares the same signature.

    Yields
    ------
    Tuple[Dict[str, str], int]
        A ``({"label": ..., "seq_len": ...}, answer)`` pair per label.
    """
    seq_len = max(pos_to_compound.keys())
    for period, label in sorted(period_to_label.items()):
        yield {"label": label, "seq_len": str(seq_len)}, seq_len // period


