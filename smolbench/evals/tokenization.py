"""
Tokenize prompts for the model under test, to size token-matched prompts.

Why this exists
----------------
The induction benchmarks' ``noise_intens`` arm is a LENGTH CONTROL: this
arm pads the intensional (rule) context until its prompt is "the same
length" as the extensional (full listing) prompt. This keeps an
intens-vs-extens accuracy gap from being blamed on prompt length. Length
here has to mean TOKENS, because tokens are what the model actually
consumes -- and a character-matched pad is not even close. Measured at
the periodic production config (``n=9``, seed 1776, ``cl100k_base``): the
extensional prompt is 26,279 tokens, while a character-matched
random-alphanumeric pad came to 42,639 tokens, 1.62x its target. Random
characters tokenize far worse than structured text, so matching
characters silently OVER-pads the control.

A pad's size in tokens needs a tokenizer, and the only tokenizer whose
counts describe what the model under test really sees is that model's
own. Hence this module: it maps the eval's short model alias (the key of
``ec2.EC2_DEPLOY_SPECS``, which is also vLLM's ``--served-model-name``
and the ``model`` argument threaded through ``provider.evaluate``) to a
`Tokenizer` for that exact checkpoint.

No silent fallbacks
--------------------
Every constructor here raises when it cannot load its tokenizer. This is
deliberate, and it differs from
`smolbench.deduction.lean.context._count_tokens`, which falls back to a
``len(s) // 4`` estimate. That function only gates INTERNAL budget
decisions (how much premise text to include), so a sloppy count only
costs a slightly different truncation point. Here, the count determines
PROMPT BYTES. A fallback would silently emit a differently padded prompt
under the same seed, breaking the reproducibility guarantee that a
replicate's ``rep_{seed}.yaml`` can be regenerated byte-for-byte from its
filename. An error is strictly better than a quiet de-calibration.

Dependencies
------------
`HFTokenizer` deliberately uses ``huggingface_hub`` + ``tokenizers``
rather than ``transformers``. It needs one file (``tokenizer.json``) and
the Rust BPE that reads it, not the modeling stack, its torch dependency,
or its config plumbing. `TiktokenTokenizer` lazily imports ``tiktoken``
(a `lean` extra, not a core dependency). It exists for tests, and for
offline work where a model-specific tokenizer is unavailable or
unwanted; it is never selected implicitly.
"""

import functools
import logging
from typing import Any, Protocol, runtime_checkable

import requests

from smolbench.evals.openai_compat import METADATA_TIMEOUT_S


@runtime_checkable
class Tokenizer(Protocol):
    """Anything that can count a string's tokens for the model under test.

    This protocol is structural, not nominal: `HFTokenizer`,
    `TiktokenTokenizer`, `VLLMTokenizer`, and any test double all satisfy
    it without inheriting from it. This is what lets the offline test
    suite drive the token-matching machinery with a deterministic stub,
    instead of a downloaded checkpoint.
    """

    #: Human-readable identity of the tokenizer (repo id, encoding name,
    #: served model...). This is only used in error messages and log
    #: lines, so its exact format is free -- it exists so a token-match
    #: failure names WHICH tokenizer could not reach the target.
    name: str

    def count(self, text: str) -> int:
        """Return the number of tokens `text` encodes to.

        An implementation MUST exclude special/BOS tokens. A caller
        compares counts between two prompts that will each be wrapped
        identically by the chat template downstream, so a constant
        per-prompt offset is noise at best. Applied inconsistently, it
        would become an off-by-N in the match.
        """
        ...


class HFTokenizer:
    """A model's own tokenizer, loaded from its HuggingFace ``tokenizer.json``.

    This is the tokenizer that actually describes what the served
    checkpoint consumes, so the induction benchmarks use it to size the
    noise pad for the model currently under test.
    """

    def __init__(self, name: str, tokenizer: Any) -> None:
        """Wrap an already-constructed ``tokenizers.Tokenizer``.

        Prefer `from_repo`, which resolves and caches the download. This
        constructor stays public so a caller holding a tokenizer object
        from elsewhere (a local checkout, a test fixture) can adapt it
        without touching the network.

        Parameters
        ----------
        name : str
            Identity for logs/errors, conventionally the HF repo id.
        tokenizer : Any
            A ``tokenizers.Tokenizer`` instance (duck-typed: anything with
            ``encode(text, add_special_tokens=False).ids``).
        """
        self.name = name
        self._tokenizer = tokenizer

    @classmethod
    def from_repo(cls, repo_id: str) -> "HFTokenizer":
        """Download (once, then cached) and load `repo_id`'s tokenizer.

        Parameters
        ----------
        repo_id : str
            HuggingFace repo id, e.g. ``"openai/gpt-oss-120b"``.

        Returns
        -------
        HFTokenizer

        Raises
        ------
        ImportError
            ``huggingface_hub`` or ``tokenizers`` is not installed.
        RuntimeError
            The repo has no ``tokenizer.json`` (some quantized
            redistributions ship weights only), or the download/parse
            fails. The message names the ``tokenizer_hf_id`` deploy-spec
            key that overrides which repo the tokenizer comes from.

        Notes
        -----
        This function fetches only ``tokenizer.json`` -- a few MB, versus
        hundreds of GB of weights -- into the ordinary
        ``~/.cache/huggingface`` hub cache. The first call needs network;
        later calls do not.

        TRUNCATION IS DISABLED on load, and this is load-bearing rather
        than tidiness. A ``tokenizer.json`` may embed a ``truncation``
        stanza, and ``tokenizers`` honors it on every ``encode``. So
        ``count`` would SATURATE at that cap instead of measuring the
        string. ``nvidia/Llama-3_1-Nemotron-Ultra-253B-v1-FP8`` ships
        ``{"max_length": 512}``, which reported a ~26,000-token induction
        prompt as 512 tokens. Both the extensional prompt and its noise
        pad would then measure 512, the padding search would call them
        matched, and the length control would be silently, wildly wrong
        -- the exact failure this module exists to prevent. Padding is
        disabled for the same reason in the other direction: a padded
        batch would count tokens the model never sees.
        """
        try:
            from huggingface_hub import hf_hub_download
            from tokenizers import Tokenizer as HFTokenizerImpl
        except ImportError as exc:  # pragma: no cover -- both are core deps
            raise ImportError(
                "HFTokenizer needs `huggingface_hub` and `tokenizers` "
                f"(pip install smolbench): {exc}"
            ) from exc
        try:
            path = hf_hub_download(repo_id=repo_id, filename="tokenizer.json")
        except Exception as exc:  # noqa: BLE001 -- hub raises a wide family here
            raise RuntimeError(
                f"could not fetch tokenizer.json from {repo_id!r}: "
                f"{type(exc).__name__}: {exc}. If this repo ships weights "
                "only (common for quantized redistributions), point the "
                "deploy spec's `tokenizer_hf_id` key at a repo that has the "
                "tokenizer -- normally the unquantized base model."
            ) from exc
        tokenizer = HFTokenizerImpl.from_file(path)
        tokenizer.no_truncation()
        tokenizer.no_padding()
        return cls(repo_id, tokenizer)

    def count(self, text: str) -> int:
        """Return `text`'s token count under this checkpoint's tokenizer."""
        return len(self._tokenizer.encode(text, add_special_tokens=False).ids)


class TiktokenTokenizer:
    """A fixed ``tiktoken`` encoding, for tests and offline/tokenizer-free work.

    This is NOT a stand-in for the model under test -- ``cl100k_base`` is
    nobody's tokenizer among the served checkpoints. It exists because it
    is deterministic, dependency-light, and locally cached, which makes
    it a good driver for regression tests and for eyeballing prompt sizes
    with no network round trip. A caller must select it explicitly;
    nothing in this module falls back to it.
    """

    def __init__(self, encoding_name: str = "cl100k_base") -> None:
        """Load a ``tiktoken`` encoding by name.

        Parameters
        ----------
        encoding_name : str
            Any name ``tiktoken.get_encoding`` accepts, e.g.
            ``"cl100k_base"`` (GPT-4 family) or ``"o200k_base"`` (GPT-4o /
            gpt-oss family).

        Raises
        ------
        ImportError
            ``tiktoken`` is not installed; it lives in the ``lean``
            extra, not the core dependency set.
        """
        try:
            import tiktoken
        except ImportError as exc:  # pragma: no cover -- optional extra
            raise ImportError(
                "TiktokenTokenizer needs `tiktoken` "
                f"(pip install 'smolbench[lean]'): {exc}"
            ) from exc
        self.name = f"tiktoken:{encoding_name}"
        self._encoding = tiktoken.get_encoding(encoding_name)

    def count(self, text: str) -> int:
        """Return `text`'s token count under this encoding."""
        return len(self._encoding.encode(text))


class VLLMTokenizer:
    """Count tokens by asking a LIVE vLLM server's ``/tokenize`` endpoint.

    This is the ground truth for "what the served model sees", and
    therefore the cross-check that `HFTokenizer` really did load the
    right tokenizer. It is NOT for the generation hot path. Sizing one
    noise pad takes a handful of count() calls per question, and paying
    an HTTP round trip on a ~55 KB prompt for each of them would dwarf
    the eval itself. Use `for_model` (local, in-process) to build
    prompts, and this class to verify them.
    """

    def __init__(self, base_url: str, model: str, api_key: str) -> None:
        """Bind to one served model on one vLLM server.

        Parameters
        ----------
        base_url : str
            The OpenAI-compatible base URL, e.g.
            ``"http://1.2.3.4:8000/v1"`` (``ec2._base_url()``). vLLM
            serves ``/tokenize`` at the SERVER root rather than under
            ``/v1``, so this constructor strips a trailing ``/v1``.
        model : str
            vLLM's ``--served-model-name`` (the eval's model alias).
        api_key : str
            Bearer token for the server (``ec2._api_key()``).
        """
        root = base_url.rstrip("/")
        if root.endswith("/v1"):
            root = root[: -len("/v1")]
        self.name = f"vllm:{model}@{root}"
        self._url = f"{root}/tokenize"
        self._model = model
        self._api_key = api_key

    def count(self, text: str) -> int:
        """Return `text`'s token count as reported by the live server.

        Raises
        ------
        requests.HTTPError
            The endpoint rejects the request. vLLM exposes ``/tokenize``
            by default; a 404 means the server predates it, or was
            launched with the endpoint disabled.
        """
        response = requests.post(
            self._url,
            headers={"Authorization": f"Bearer {self._api_key}"},
            json={"model": self._model, "prompt": text, "add_special_tokens": False},
            timeout=METADATA_TIMEOUT_S,
        )
        response.raise_for_status()
        return int(response.json()["count"])


@functools.lru_cache(maxsize=None)
def for_model(model: str) -> Tokenizer:
    """Return the tokenizer of the checkpoint served under alias `model`.

    The alias is a key of ``ec2.EC2_DEPLOY_SPECS`` -- the same string a
    notebook passes to ``provider.evaluate``, and that vLLM serves under
    -- and the tokenizer comes from that spec's ``hf_model_id`` (or its
    ``tokenizer_hf_id`` override, for weights-only quantized repos).

    Parameters
    ----------
    model : str
        Eval model alias, e.g. ``"qwen3.5-397b-a17b"``.

    Returns
    -------
    Tokenizer
        An `HFTokenizer`, memoized per alias for the life of the
        process. Loading is a file parse, and the induction generators
        call this once per replicate per model.

    Raises
    ------
    KeyError
        No deploy spec names `model`. A caller evaluating a model outside
        the spec table must construct a `Tokenizer` itself, and pass it
        in explicitly.

    Notes
    -----
    This function imports ``smolbench.evals.ec2`` INSIDE itself, never at
    module scope. ``ec2.py``'s ``EC2_*`` module constants are captured
    from ``os.environ`` at IMPORT time, so an eager import here would
    freeze them for any notebook that imports the induction stack before
    its ``load_dotenv(keys.env)`` cell runs -- the same constraint
    documented at length in ``smolbench.induction.experiment``. Deferring
    the import keeps this module safe to import from anywhere.
    """
    from smolbench.evals import ec2

    spec = ec2.EC2_DEPLOY_SPECS.get(model)
    if spec is None:
        raise KeyError(
            f"no EC2_DEPLOY_SPECS entry for model {model!r}; pass a "
            "Tokenizer explicitly for models outside the spec table"
        )
    repo_id: str = spec.get("tokenizer_hf_id") or spec["hf_model_id"]
    logging.info(f"tokenization.for_model: {model!r} -> {repo_id}")
    return HFTokenizer.from_repo(repo_id)

